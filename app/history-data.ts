export function formatYear(year: number) {
  if (year < 0) return `公元前${Math.abs(year)}年`;
  return `${year}年`;
}

export function findPeriodForYear(year: number) {
  return periods.find((period) => year >= period.start && year <= period.end) ?? periods[periods.length - 1];
}
